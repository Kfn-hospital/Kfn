-- بيسمح لأي مستخدم إنه يشوف صف صلاحيته هو بس في file_uploaders
-- (كانت السياسة القديمة بتقصر القراءة على الأدمن بس، فكانت صلاحية رفع
-- الملفات المُمنوحة لموظف عادي مش بتظهر له لأنه مش قادر يقرأ صفه).
drop policy if exists "المستخدم يشوف صلاحيته هو في رفع الملفات" on file_uploaders;

create policy "المستخدم يشوف صلاحيته هو في رفع الملفات" on file_uploaders
  for select using (auth.uid() = user_id);
